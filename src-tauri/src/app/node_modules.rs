use tauri::{AppHandle, Emitter};

use crate::app::llama_server::format_file_size;

// ===== 命令：扫描 node_modules =====

#[derive(Debug, Clone, serde::Serialize)]
pub(crate) struct NodeModulesInfo {
    path: String,
    project_path: String,
    size_bytes: u64,
    size_display: String,
    project_name: String,
    has_pnpm_lock: bool,
}

#[tauri::command]
pub(crate) async fn scan_node_modules(
    app: AppHandle,
    workspace_path: String,
    max_depth: Option<usize>,
) -> Result<Vec<NodeModulesInfo>, String> {
    tokio::task::spawn_blocking(move || {
        use std::fs;
        use std::path::Path;

        let max_depth = max_depth.unwrap_or(15);
        let mut results: Vec<NodeModulesInfo> = Vec::new();

        fn scan_dir(
            app: &AppHandle,
            path: &Path,
            depth: usize,
            max_depth: usize,
            results: &mut Vec<NodeModulesInfo>,
        ) {
            if depth > max_depth {
                return;
            }
            if !path.exists() || !path.is_dir() {
                return;
            }

            // 顶层及项目目录扫描时通知前端当前进度
            if depth <= 1 {
                let name = path
                    .file_name()
                    .and_then(|n| n.to_str())
                    .map(|s| s.to_string())
                    .unwrap_or_else(|| path.to_string_lossy().to_string());
                let _ = app.emit("nm-scan-progress", name);
            }

            if let Ok(entries) = fs::read_dir(path) {
                for entry in entries.flatten() {
                    let entry_path = entry.path();
                    if !entry_path.is_dir() {
                        continue;
                    }

                    if entry_path
                        .file_name()
                        .map(|n| n == "node_modules")
                        .unwrap_or(false)
                    {
                        let size = get_dir_size(&entry_path);
                        let parent_path = entry_path.parent();
                        let project_name = parent_path
                            .and_then(|p| p.file_name())
                            .and_then(|n| n.to_str())
                            .unwrap_or("unknown")
                            .to_string();

                        // 检测父目录是否有 pnpm-lock.yaml
                        let has_pnpm_lock = parent_path
                            .map(|p| p.join("pnpm-lock.yaml").exists())
                            .unwrap_or(false);

                        let project_path = parent_path
                            .map(|p| p.to_string_lossy().to_string())
                            .unwrap_or_default();

                        results.push(NodeModulesInfo {
                            path: entry_path.to_string_lossy().to_string(),
                            project_path,
                            size_bytes: size,
                            size_display: format_file_size(size),
                            project_name,
                            has_pnpm_lock,
                        });
                        // 不再递归进入 node_modules 内部
                    } else {
                        let name = entry_path
                            .file_name()
                            .and_then(|n| n.to_str())
                            .unwrap_or("");
                        if !name.starts_with('.')
                            && name != "target"
                            && name != "dist"
                            && name != "build"
                        {
                            scan_dir(app, &entry_path, depth + 1, max_depth, results);
                        }
                    }
                }
            }
        }

        scan_dir(&app, Path::new(&workspace_path), 0, max_depth, &mut results);
        results.sort_by(|a, b| b.size_bytes.cmp(&a.size_bytes));
        app_log!(
            info,
            "node_modules",
            "scan ok: {} found ({})",
            results.len(),
            workspace_path
        );
        Ok(results)
    })
    .await
    .map_err(|e| format!("扫描任务失败: {}", e))?
}

pub(crate) fn get_dir_size(path: &std::path::Path) -> u64 {
    use std::fs;

    let mut total_size: u64 = 0;

    if path.is_dir() {
        if let Ok(entries) = fs::read_dir(path) {
            for entry in entries.flatten() {
                let entry_path = entry.path();
                if entry_path.is_dir() {
                    total_size += get_dir_size(&entry_path);
                } else if entry_path.is_file() {
                    if let Ok(metadata) = entry.metadata() {
                        total_size += metadata.len();
                    }
                }
            }
        }
    }

    total_size
}

#[derive(Debug, serde::Serialize)]
pub(crate) struct CleanResult {
    success: bool,
    cleaned_paths: Vec<String>,
    failed_paths: Vec<(String, String)>, // (path, error message)
    total_freed_bytes: u64,
    total_freed_display: String,
}

#[tauri::command]
pub(crate) async fn clean_node_modules(paths: Vec<String>) -> Result<CleanResult, String> {
    tokio::task::spawn_blocking(move || {
        use std::fs;

        let mut cleaned_paths: Vec<String> = Vec::new();
        let mut failed_paths: Vec<(String, String)> = Vec::new();
        let mut total_freed_bytes: u64 = 0;

        for path in paths {
            let path_obj = std::path::Path::new(&path);
            if !path_obj.exists() {
                failed_paths.push((path.clone(), "路径不存在".to_string()));
                continue;
            }

            let size = get_dir_size(path_obj);

            match fs::remove_dir_all(path_obj) {
                Ok(_) => {
                    // 破坏性操作，必须逐条落盘
                    app_log!(
                        info,
                        "node_modules",
                        "clean removed: {} ({} bytes)",
                        path,
                        size
                    );
                    cleaned_paths.push(path.clone());
                    total_freed_bytes += size;
                }
                Err(e) => {
                    app_log!(error, "node_modules", "clean failed: {} ({})", path, e);
                    failed_paths.push((path, e.to_string()));
                }
            }
        }

        app_log!(
            info,
            "node_modules",
            "clean done: {} cleaned, {} failed, freed {}",
            cleaned_paths.len(),
            failed_paths.len(),
            format_file_size(total_freed_bytes)
        );

        Ok(CleanResult {
            success: failed_paths.is_empty(),
            cleaned_paths,
            failed_paths,
            total_freed_bytes,
            total_freed_display: format_file_size(total_freed_bytes),
        })
    })
    .await
    .map_err(|e| format!("清理任务失败: {}", e))?
}
